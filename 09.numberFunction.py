# 숫자 처리 함수
print("===== 숫자 처리 함수 =====")

print(abs(-5)) # 5 => 절대값
print(pow(4, 2)) # 4^2 => 제곱
print(max(5, 12, 3)) # 12 => 최대값
print(min(5, 12, 3)) # 3 => 최소값
print(round(3.14)) # 3 => 반올림
print(round(4.99)) # 5 => 반올림

from math import * # 파이썬에서 제공하는 math 라이브러리 사용
print(floor(4.99)) # 4 => 내림
print(ceil(3.14)) # 4 => 올림
print(sqrt(16)) # 4 => 제곱근


